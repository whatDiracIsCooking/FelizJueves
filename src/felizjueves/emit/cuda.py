"""The CUDA backend: a `Kernel` rendered as CUDA C++, for an NVIDIA `Arch`.

    emit(kernel, arch) -> str

A pure function: no decisions, no I/O. Everything CUDA and HIP spell alike is
`emit/_c.py`'s `CWriter`; this module supplies only what CUDA spells its own
way:

- the prologue: a header comment naming the kernel and the arch, and no
  include (nvcc pre-includes the CUDA runtime for a `.cu`);
- `WarpReduce` as the xor butterfly the interpreter models (`v += shfl_xor(v,
  o)` for o = width/2 .. 1), with `__shfl_xor_sync` over the full mask of the
  arch's wavefront -- the width is read off the `Arch`, never spelled here;
- `LaneBroadcast` (#349) as `__shfl_sync(mask, value, source, width)`, the
  same full mask and width;
- `AtomicAdd` as `atomicAdd` (the shared default; double is native on sm_60+).

The arch string is what nvcc is driven at (`-arch=<arch.name>`); it is not in
the source, which compiles for any NVIDIA arch with this wavefront.
"""

from __future__ import annotations

from felizjueves.emit._c import CWriter, precision
from felizjueves.ir import Kernel
from felizjueves.performance.device import Arch, Vendor

__all__ = ["emit"]


class CudaWriter(CWriter):
    def __init__(self, arch: Arch) -> None:
        super().__init__(arch)
        if arch.vendor is not Vendor.NVIDIA:
            raise ValueError(f"the CUDA backend emits for NVIDIA, not {arch.vendor}")

    def prologue(self, k: Kernel) -> str:
        a = self.arch
        return (
            f"// {k.name}: generated by felizjueves.emit.cuda -- do not edit.\n"
            f"// arch {a.name}, wavefront {a.wavefront}; {precision(k)}.\n"
        )

    def warp_reduce(self, dst: str, value: str) -> list[str]:
        w = self.arch.wavefront
        mask = f"0x{(1 << w) - 1:x}u"
        return [
            "{",
            f"    auto fj_v = {value};",
            f"    for (int fj_o = {w // 2}; fj_o > 0; fj_o /= 2) {{",
            f"        fj_v += __shfl_xor_sync({mask}, fj_v, fj_o, {w});",
            "    }",
            f"    {dst} = fj_v;",
            "}",
        ]

    def lane_broadcast(self, dst: str, value: str, lane: str) -> str:
        # #349: the indexed shuffle over the full mask of the arch's width.
        w = self.arch.wavefront
        mask = f"0x{(1 << w) - 1:x}u"
        return f"{dst} = __shfl_sync({mask}, {value}, {lane}, {w});"


def emit(kernel: Kernel, arch: Arch) -> str:
    """Render a Kernel as CUDA C++. No decisions."""
    return CudaWriter(arch).kernel(kernel)
